import re
import json
import os
import requests

import google.generativeai as genai

from dotenv import load_dotenv

from get_numbers import get_numbers_func
# from json_to_txt import get_examples_text

load_dotenv()


with open("examples.txt", "r", encoding="utf-8") as f:
    examples_text = f.read()

# examples_text = get_examples_text()


GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")
genai.configure(api_key=GEMINI_API_KEY)

ID_INSTANCE = os.getenv("ID_INSTANCE")
API_TOKEN_INSTANCE = os.getenv("API_TOKEN_INSTANCE")
API_URL = os.getenv("API_URL")
CLIENT_PHONE_NUMBER = os.getenv("CLIENT_PHONE_NUMBER")

minutes = 600
numbers = get_numbers_func(f"{API_URL}/waInstance{ID_INSTANCE}/lastIncomingMessages/{API_TOKEN_INSTANCE}?minutes={minutes}")

output_file = "results/results.txt"
os.makedirs(os.path.dirname(output_file), exist_ok=True)
with open(output_file, "w", encoding="utf-8") as f:
    f.write("=== РЕЗУЛЬТАТЫ КЛАССИФИКАЦИИ ДИАЛОГОВ ===\n\n")

for idx, number in enumerate(numbers, start=1):
    url = f"{API_URL}/waInstance{ID_INSTANCE}/getChatHistory/{API_TOKEN_INSTANCE}"

    payload = {
        "chatId": f"{number}@c.us", 
        "count": 30
    }
    headers = {
    'Content-Type': 'application/json'
    }

    response = requests.post(url, json=payload)
    messages = response.json()
    messages = list(reversed(messages))

    chat_history = """"""
    deal_start_time = 0 # ПЕРЕМЕННАЯ ДЛЯ ВРЕМЕНИ НАЧАЛА СДЕЛКИ 


    for message in messages:
        if message["timestamp"] < deal_start_time:
            continue
        if message["type"] == "outgoing":
            chat_history += "Оператор:\n"
        elif message["type"] == "incoming":
            chat_history += "Клиент:\n"
        if message.get("textMessage"):
            chat_history += message["textMessage"]
        if message.get("extendedTextMessage"):
                chat_history += message.get("extendedTextMessage")["text"]
        chat_history += "\n\n"

    # print(chat_history)


    system_prompt = f"""
    Ты — интеллектуальный классификатор обращений клиентов оптики.

    ### Твоя основная задача:
    Определи:
    1. **Причину обращения клиента** (обязательно)
    2. **Причину отказа**, если она явно или неявно присутствует в чате (опционально)

    ---

    ### 1. Причина обращения (reason) 
    Определи, чего хочет клиент, исходя из смысла диалога или первого сообщения. 
    Выбирай **только одну категорию** из списка ниже. 
    Если это автоуведомление или клиент ничего не просил — укажи “Уведомления”.

    ---

    **Список возможных категорий:** 1. Услуга подбора очков (проверка) — клиент хочет записаться на диагностику зрения, без заболеваний, старше 18 лет. 
    2. Услуга подбора МКЛ (проверка) — диагностика для подбора контактных линз (часто выясняется по ходу диалога). 
    3. Услуга детская проверка зрения — клиент хочет проверку зрения для ребёнка (до 18 лет). 
    4. Услуга лечения глаз — клиент описывает жалобы или спрашивает о лечении.
    5. Услуга ремонта очков — клиент спрашивает о ремонте оправ или линз. 
    6. Услуга трейд-ин — интересуется программой трейд-ин, условиями обмена и скидками. 
    7. Услуга сверки очков на точность — жалуется на дискомфорт в очках, подозревает, что ему неправильно проверили зрение и хочет перепроверить у нас. Либо же купил очки у нас и чувствует дискомфорт. 
    8. Купить очки для зрения — хочет полностью подобрать очки (оправа + линзы). Выбирать если цель клиента - конкретно купить очки (оправа + линзы). Если он не уверен, что ему нужны очки, и хочет сначала провериться, нужно выбирать "Услуга подбора очков (проверка)". 
    9. Купить очковые линзы — интересуется покупкой линз (прогрессивные, фотохромные, компьютерные и т.д.). Выбирать эту причину только если клиенту не нужна диагностика. Если же нужна - выбирать "Услуга подбора очков (проверка)". 
    10. Купить СЗ — хочет солнцезащитные очки, скидывает модель или уточняет наличие. 
    11. Купить МКЛ — хочет купить контактные линзы (уточняет наличие, цены, варианты). 
    12. Купить подарочный сертификат — спрашивает про сертификаты, сроки, оплату, условия. 
    13. Покупка повторного заказа очков для зрения — хочет повторить свой старый заказ. 
    14. Узнать статус заказа — клиент сам спрашивает, готов ли заказ, когда забрать. 
    15. Сотрудничество — пишет о партнёрстве, интеграциях, услугах для бизнеса. 
    16. Найм — интересуется вакансиями. 
    17. Уведомления — автоуведомления, поздравления, напоминания, случайные сообщения, смайлы. 
    18. Отзывы и обратная связь — выражает благодарность, жалобы, пожелания. 
    19. Не ответил — клиент не отвечает ни по телефону, ни в чате. 
    20. Закрыта автоматически — до клиента не дошло сообщение (например, закрытый аккаунт в Instagram). 
    
    --- 
    
    ### 2. Причина отказа (refusal_reason) 
    Определи, почему клиент **не записался** или **отказался от визита**, если это видно в диалоге. 
    Если договорились с клиентом на запись — оставь null. 
    
    **Список возможных причин отказа:** 
    1. Детская проверка — клиент/родитель хотел диагностику ребёнку, но не можем принять до 18 лет. 
    2. Лечение либо другие мед услуги — у клиента жалобы или мед. противопоказания. 
    3. Другой город — клиент находится в другом городе. 
    4. Хочет купить онлайн, без визита — оформляет покупку онлайн (линзы, сертификаты, повторные очки). 
    5. Сказал, что сам придет в оптику — не хочет запись, просто придёт сам с рецептом. 
    6. Дубль заявки — дублирующий диалог (например, по статусу заказа или уведомлению). 
    7. Не устраивает цена — отказ после озвучивания цены. 
    8. Не устраивает срок изготовления — отказ из-за длительного ожидания. 
    9. Нет нужного товара/услуги по ремонту — отказ, потому что не можем отремонтировать или нет нужных деталей. 
    10. Не подошло время приема — неудобное время, командировка, вахта, ждёт зарплату. 
    11. Неудобная локация — адреса не подошли. 
    12. Купил в другом месте — сообщил, что уже приобрёл где-то ещё. 
    13. Нет связи с клиентом — перестал отвечать, не выходит на связь. 
    14. Спам / уведомления — случайные или нецелевые сообщения. 
    15. Закрыта автоматически — сообщение не доставлено из-за настроек мессенджера. 
    16. Сотрудничество (передал ответственному) — обращение о партнёрстве или найме передано ответственным.
    ---

    ### Формат ответа:
    Ответ должен быть **строго в формате JSON**, без комментариев и лишнего текста.
    {{
        "reason": "<название категории причины обращения>",
        "refusal_reason": "<название категории причины отказа>" || null
    }}

    ---

    {examples_text}

    ---

    Теперь классифицируй по следующей истории сообщений с клиентом:
    """


    model = genai.GenerativeModel("models/gemini-2.5-flash")

    response = model.generate_content(
        [
            {"role": "user", "parts": system_prompt + "\n" + chat_history}
        ],
        generation_config=genai.types.GenerationConfig(
            temperature=0.0,
        )
    )

    answer = response.text.strip() if response.text else ""

    result_text = f"=== Диалог {idx} ({number}) ===\n\n"
    result_text += f"История сообщений:\n{chat_history}\n"
    result_text += "Ответ модели:\n"

    if not answer:
        result_text += "❌ Модель не вернула текстовый ответ.\n"
    else:
        cleaned = re.sub(r"^```json|```$", "", answer.strip(), flags=re.MULTILINE).strip()
        try:
            data = json.loads(cleaned)
            result_text += json.dumps(data, ensure_ascii=False, indent=2) + "\n"
        except json.JSONDecodeError:
            result_text += f"Ошибка парсинга JSON. Ответ модели:\n{answer}\n"

    result_text += "\n" + "=" * 50 + "\n\n"

    # === Записываем результат в файл ===
    with open(output_file, "a", encoding="utf-8") as f:
        f.write(result_text)
    
print(f"✅ Все результаты сохранены в {output_file}")
